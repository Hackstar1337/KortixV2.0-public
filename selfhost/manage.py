def validate_ports(config: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    ports = config.get("ports")
    if not isinstance(ports, dict):
        return ["ports must be an object"]
    for name in DEFAULT_PORTS:
        value = ports.get(name)
        if not isinstance(value, int) or not 1 <= value <= 65535:
            errors.append(f"ports.{name} must be an integer from 1 to 65535")
    if len(set(ports.get(name) for name in DEFAULT_PORTS if isinstance(ports.get(name), int))) != len(DEFAULT_PORTS):
        errors.append("published ports must be distinct")
    return errors


def validate_compose(compose: Path) -> list[str]:
    if not compose.is_file():
        return [f"missing Compose file: {compose}"]
    text = compose.read_text(encoding="utf-8")
    errors: list[str] = []
    # Every published host port in the source-owned stack must be loopback-bound.
    in_ports = False
    ports_indent = -1
    for number, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        indent = len(line) - len(line.lstrip())
        if stripped == "ports:":
            in_ports = True
            ports_indent = indent
            continue
        if in_ports and stripped and indent <= ports_indent:
            in_ports = False
        if in_ports and stripped.startswith("-") and ":" in stripped:
            mapping = stripped[1:].strip().strip("\"'")
            if not mapping.startswith("127.0.0.1:"):
                errors.append(f"Compose line {number} publishes a non-loopback port")
    if "kortix-migrate" not in text or "migrate.ts" not in text or "bootstrap" not in text:
        errors.append("Compose must retain the upstream kortix-migrate bootstrap command")
    return errors


def copy_bundled_assets(instance: Path) -> None:
    """Copy source-owned runtime assets without overwriting operator files."""
    bundled = Path(__file__).resolve().parent
    files = ((bundled / "Caddyfile.txt", instance / "Caddyfile"), (bundled / "updater.sh", instance / "updater.sh"))
    for source, destination in files:
        if source.is_file() and not destination.exists():
            shutil.copyfile(source, destination)
    source_dir = bundled / "supabase" / "volumes"
    destination_dir = instance / "volumes"
    if source_dir.is_dir() and not destination_dir.exists():
        shutil.copytree(source_dir, destination_dir)


def write_runtime_overlay(instance: Path, config: dict[str, Any], materialize_tunnel: bool) -> None:
    """Keep production off Quick Tunnels and read named-tunnel tokens from a file."""
    services: dict[str, Any] = {"kortix-updater":{"profiles":["upstream-updater-disabled"],"restart":"no"}, "frontend":{"environment":{"KORTIX_SUPABASE_PROXY_TARGET":"http://supabase-kong:8000","KORTIX_API_PROXY_TARGET":"http://kortix-api:8008"}}}
    token_file = path_from_config(instance, config.get("tunnel_token_file"))
    if token_file:
        if not token_file.is_file():
            raise ManagerError("named-tunnel token file does not exist")
        if materialize_tunnel:
            token_value = token_file.read_text(encoding="utf-8").strip()
            if not token_value or "\n" in token_value or "\r" in token_value:
                raise ManagerError("named-tunnel token file must contain one non-empty token line")
        services["cloudflared"] = {
            "user":"0:0", "cap_drop":["ALL"], "security_opt":["no-new-privileges:true"],
            "environment":{"TUNNEL_TOKEN":"", "TUNNEL_TOKEN_FILE":"/run/secrets/named-tunnel-token"},
            "volumes":[{"type":"bind","source":str(token_file.resolve()),"target":"/run/secrets/named-tunnel-token","read_only":True}],
            "command":["tunnel","--no-autoupdate","--protocol","http2","run","--token-file","/run/secrets/named-tunnel-token"],
        }
    elif config.get("mode") == "production":
        # The upstream template's default cloudflared command is a Quick Tunnel.
        # Exclude that service unless a named token is explicitly configured.
        services["cloudflared"] = {"profiles": ["development-quick-tunnel"]}
    overlay = instance / "docker-compose.reachability.yml"
    if services:
        private_write(overlay, json.dumps({"services": services}, indent=2) + "\n")
    # Do not delete an operator-owned overlay. A fresh instance has no file.


def credential_values(path: Path) -> dict[str, str]:
    if not path.is_file():
        raise ManagerError(f"Docker Cloud credential file does not exist: {path}")
    values = parse_env(path)
    missing = [key for key in CREDENTIAL_KEYS if not values.get(key, "").strip()]
    if missing:
        raise ManagerError("Docker Cloud credential file needs Docker ID and Cloud-enabled PAT")
    if any("\n" in value or "\r" in value for value in values.values()):
        raise ManagerError("Docker Cloud credential values cannot contain newlines")
    return {key: values[key].strip() for key in CREDENTIAL_KEYS}


def write_backend_overlay(instance: Path, config: dict[str, Any], credentials: dict[str, str]) -> None:
    private_write(instance / ".docker-cloud.env", "".join(f"{key}={value}\n" for key, value in credentials.items()))
    overlay = {
        "services": {
            "kortix-api": {
                "env_file": [".env", ".docker-cloud.env"],
                "environment": {"ALLOWED_SANDBOX_PROVIDERS": ",".join(config["providers"])},
            }
        }
    }
    private_write(instance / "docker-compose.docker-cloud.yml", json.dumps(overlay, indent=2) + "\n")


def config_from_args(args: argparse.Namespace, existing: dict[str, Any] | None = None) -> dict[str, Any]:
    old = existing or {}
    mode = args.mode or old.get("mode") or "production"
    callback = args.callback_url or old.get("callback_url") or DEFAULT_CALLBACK
    frontend = args.frontend_url or old.get("frontend_url") or DEFAULT_FRONTEND
    providers = (args.providers.split(",") if args.providers else old.get("providers") or DEFAULT_PROVIDERS)
    providers = [item.strip().lower() for item in providers if item.strip()]
    return {
        "schema_version": SCHEMA_VERSION,
        "project_name": args.project_name or old.get("project_name") or DEFAULT_PROJECT,
        "mode": mode,
        "callback_url": callback,
        "frontend_url": frontend,
        "compose_file": old.get("compose_file") or DEFAULT_COMPOSE,
        "providers": providers,
        "docker_cloud_resources": {**DEFAULT_RESOURCES, **old.get("docker_cloud_resources", {})},
        "docker_cloud_credentials_file": args.docker_cloud_credentials or old.get("docker_cloud_credentials_file") or "",
        "tunnel_token_file": args.named_tunnel_token_file or old.get("tunnel_token_file") or "",
        "kortix_bin": args.kortix_bin or old.get("kortix_bin") or "",
        "admin_email": args.admin_email or old.get("admin_email") or "",
        "ports": {**DEFAULT_PORTS, **old.get("ports", {})},
    }


def doctor(instance: Path, config: dict[str, Any], check_docker: bool = False) -> tuple[list[str], list[str]]:
    errors = validate_ports(config)
    warnings: list[str] = []
    if config.get("mode") not in ("production", "development"):
        errors.append("mode must be production or development")
    if not config.get("admin_email"):
        warnings.append("Set --admin-email during init to authorize the operator's account; register that address through the password signup screen")
    production = config.get("mode") == "production"
    ok, detail = stable_callback(str(config.get("callback_url", "")), production)
    if not ok:
        errors.append(detail)
    providers = config.get("providers")
    if not isinstance(providers, list) or not providers:
        errors.append("select at least one sandbox provider")
    if any(provider not in {"docker-cloud", "platinum"} for provider in (providers or [])):
        errors.append("providers may contain only docker-cloud and platinum")
    if "docker-cloud" in (providers or []) and config.get("docker_cloud_resources") != DEFAULT_RESOURCES:
        errors.append("Docker Cloud baseline must remain 2 CPU cores and 4 GiB")
    compose = compose_path(instance, config)
    errors.extend(validate_compose(compose))
    env_path = instance / ".env"
    if not env_path.is_file():
        errors.append(f"missing private environment file: {env_path}")
    elif os.name != "nt" and stat.S_IMODE(env_path.stat().st_mode) & 0o077:
        errors.append(".env must be owner-readable and owner-writable only")
    if env_path.is_file():
        env = parse_env(env_path)
        secret = env.get("SUPABASE_JWT_SECRET", "")
        if not secret or secret != env.get("JWT_SECRET"):
            errors.append("Supabase JWT secret aliases must match")
        for key,role in (("ANON_KEY","anon"),("SUPABASE_ANON_KEY","anon"),("SERVICE_ROLE_KEY","service_role"),("SUPABASE_SERVICE_ROLE_KEY","service_role")):
            if not valid_supabase_jwt(env.get(key,""),role,secret):
                errors.append(key + " must be a signed HS256 token matching this instance's JWT secret")
        if len(env.get("REALTIME_DB_ENC_KEY",""))!=16 or len(env.get("VAULT_ENC_KEY",""))!=32:
            errors.append("Supabase encryption-key lengths do not match the source-owned bootstrap")
        if any(env.get(key) for key in CREDENTIAL_KEYS):
            errors.append("Docker Cloud credentials cannot be in the shared .env")
    credentials = path_from_config(instance, config.get("docker_cloud_credentials_file"))
    if "docker-cloud" in (providers or []):
        if credentials is None or not credentials.is_file():
            errors.append("Docker Cloud is selected but its backend credential file is missing")
        if (instance / ".docker-cloud.env").exists():
            if os.name != "nt" and stat.S_IMODE((instance / ".docker-cloud.env").stat().st_mode) & 0o077:
                errors.append(".docker-cloud.env must be owner-readable and owner-writable only")
    tunnel = path_from_config(instance, config.get("tunnel_token_file"))
    if tunnel:
        if not tunnel.is_file():
            errors.append("named-tunnel token file does not exist")
        elif os.name != "nt" and stat.S_IMODE(tunnel.stat().st_mode) & 0o077:
            errors.append("named-tunnel token file must be owner-readable and owner-writable only")
    binary = str(config.get("kortix_bin") or "")
    if binary and not Path(binary).is_file():
        errors.append("configured --kortix-bin does not exist")
    if config.get("mode") == "development":
        warnings.append("development mode permits localhost and Quick Tunnel callbacks; do not use it for production")
    if "platinum" in (providers or []):
        warnings.append("Platinum is retained as an optional fallback; no license or entitlement bypass is enabled")
    if check_docker:
        if shutil.which("docker") is None:
            errors.append("Docker executable is not available")
        else:
            result = subprocess.run(
                compose_command(instance, config, "config") + ["--quiet"],
                cwd=str(instance), capture_output=True, text=True,
            )
            if result.returncode != 0:
                errors.append("Docker Compose rejected the generated configuration")
    return errors, warnings


def plan(instance: Path, config: dict[str, Any], action: str, apply: bool = False) -> dict[str, Any]:
    errors, warnings = doctor(instance, config)
    credentials = path_from_config(instance, config.get("docker_cloud_credentials_file"))
    return {
        "action": action,
        "apply": apply,
        "instance": str(instance.resolve()),
        "project": config["project_name"],
        "mode": config["mode"],
        "callback_url": config["callback_url"],
        "frontend_url": config["frontend_url"],
        "providers": config["providers"],
        "docker_cloud_resources": config["docker_cloud_resources"],
        "docker_cloud_credentials": "configured" if credentials and credentials.is_file() else "required-on-apply",
        "tunnel_token": "file-configured" if config.get("tunnel_token_file") else "not-configured",
        "changes": ["start or stop existing Compose services only", "retain all volumes and user data", "inject Docker Cloud credentials into API only"],
        "deletes_data": False,
        "errors": errors,
        "warnings": warnings,
    }


def compose_command(instance: Path, config: dict[str, Any], action: str, service: str | None = None) -> list[str]:
    command = ["docker", "compose", "--project-name", str(config["project_name"]), "--env-file", str(instance / ".env"), "-f", str(compose_path(instance, config))]
    overlay = instance / "docker-compose.docker-cloud.yml"
    if overlay.is_file():
        command.extend(["-f", str(overlay)])
    reachability = instance / "docker-compose.reachability.yml"
    if reachability.is_file():
        command.extend(["-f", str(reachability)])
    command.append(action)
    if service:
        command.append(service)
    return command


def run_compose(instance: Path, config: dict[str, Any], action: str, *extra: str) -> int:
    command = compose_command(instance, config, action)
    command.extend(extra)
    if shutil.which("docker") is None:
        raise ManagerError("Docker executable is not available; plan was not applied")
    result = subprocess.run(command, cwd=str(instance), capture_output=True, text=True)
    if result.returncode:
        raise ManagerError(f"Docker Compose {action} failed; diagnostics withheld")
    if result.stdout.strip():
        print(result.stdout.strip())
    return 0


def init_instance(args: argparse.Namespace) -> int:
    instance = Path(args.instance_dir).expanduser().resolve()
    if (instance / ".env").exists() and not (instance / "config.json").exists():
        raise ManagerError("Existing unmanaged instance detected; use a migration plan rather than fresh init")
    instance.mkdir(parents=True, exist_ok=True)
    chmod_private(instance)
    config_path = instance / "config.json"
    existing = read_json(config_path) if config_path.exists() else None
    config = config_from_args(args, existing)
    ok, detail = stable_callback(config["callback_url"], config["mode"] == "production")
    if not ok:
        raise ManagerError(detail)
    source = Path(args.compose_source).expanduser().resolve() if args.compose_source else Path(__file__).with_name("compose.template.yml")
    compose = compose_path(instance, config)
    if not compose.exists():
        if not source.is_file():
            raise ManagerError(f"Compose template not found: {source}")
        shutil.copyfile(source, compose)
    copy_bundled_assets(instance)
    env_path = instance / ".env"
    env = generated_env(instance, config, parse_env(env_path))
    write_env(env_path, env)
    private_write(config_path, json.dumps(config, indent=2) + "\n")
    write_runtime_overlay(instance, config, materialize_tunnel=bool(config.get("tunnel_token_file")))
    if args.docker_cloud_credentials:
        credentials = credential_values(Path(args.docker_cloud_credentials).expanduser().resolve())
        config["docker_cloud_credentials_file"] = str(Path(args.docker_cloud_credentials).expanduser().resolve())
        private_write(config_path, json.dumps(config, indent=2) + "\n")
        write_backend_overlay(instance, config, credentials)
    print(json.dumps({"initialized": True, "instance": str(instance), "config": str(config_path), "env": str(env_path), "compose": str(compose)}, indent=2))
    return 0


def run_upstream_hint(config: dict[str, Any]) -> str:
    binary = str(config.get("kortix_bin") or "kortix")
    domain = urlparse(str(config["callback_url"])).hostname or "<domain>"
    return f"{binary} self-host init --instance {config['project_name']} --domain {domain} --yes --local-images"


def handle(args: argparse.Namespace) -> int:
    instance = Path(args.instance_dir).expanduser().resolve()
    if args.command == "init":
        return init_instance(args)
    config = load_config(instance)
    if args.command == "doctor":
        errors, warnings = doctor(instance, config, args.check_docker)
        result = {"ok": not errors, "errors": errors, "warnings": warnings}
        print(json.dumps(result, indent=2))
        return 0 if not errors else 1
    if args.command == "plan":
        result = plan(instance, config, "start", False)
        if config.get("kortix_bin"):
            result["upstream_init_command"] = run_upstream_hint(config)
        print(json.dumps(result, indent=2))
        return 0 if not result["errors"] else 1
    if args.command == "start":
        result = plan(instance, config, "start", args.apply)
        print(json.dumps(result, indent=2))
        if result["errors"]:
            return 1
        if not args.apply:
            return 0
        if os.name == "nt" and config["mode"] == "production":
            raise ManagerError("Apply production deployments on Linux through SSH; use WSL2 for local development")
        credentials_file = path_from_config(instance, config.get("docker_cloud_credentials_file"))
        if "docker-cloud" in config["providers"]:
            if credentials_file is None:
                raise ManagerError("--apply requires a private Docker Cloud credential file; never pass a PAT as an argument")
            write_backend_overlay(instance, config, credential_values(credentials_file))
        write_runtime_overlay(instance, config, materialize_tunnel=bool(config.get("tunnel_token_file")))
        return run_compose(instance, config, "up", "-d")
    if args.command == "stop":
        result = plan(instance, config, "stop", args.apply)
        print(json.dumps(result, indent=2))
        if result["errors"]:
            return 1
        if not args.apply:
            return 0
        return run_compose(instance, config, "stop")
    if args.command == "status":
        result: dict[str, Any] = {"instance": str(instance), "project": config["project_name"], "running": None, "compose": str(compose_path(instance, config))}
        if shutil.which("docker"):
            command = compose_command(instance, config, "ps")
            completed = subprocess.run(command, cwd=str(instance), capture_output=True, text=True)
            result["running"] = completed.returncode == 0
            result["docker_compose_status"] = completed.stdout.strip() if completed.returncode == 0 else "unavailable"
        else:
            result["running"] = False
            result["docker_compose_status"] = "docker unavailable"
        print(json.dumps(result, indent=2))
        return 0
    raise ManagerError(f"unsupported command: {args.command}")


def add_common(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--instance-dir", default=str(DEFAULT_INSTANCE), help="Private instance directory")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    init = sub.add_parser("init", help="Create private config and env files")
    add_common(init)
    init.add_argument("--mode", choices=("production", "development"), default=None)
    init.add_argument("--callback-url", "--api-url", dest="callback_url", default=None, help="Stable public API origin, without /v1")
    init.add_argument("--frontend-url", default=None)
    init.add_argument("--providers", "--provider", dest="providers", default=None, help="Comma-separated docker-cloud,platinum; first is default")
    init.add_argument("--project-name", default=None)
    init.add_argument("--compose-source", default=None)
    init.add_argument("--docker-cloud-credentials", default=None, help="Private file with Docker ID and Cloud-enabled PAT")
    init.add_argument("--named-tunnel-token-file", default=None, help="Path to a private named-tunnel token file")
    init.add_argument("--kortix-bin", default=None, help="Optional source-built upstream kortix binary path")
    init.add_argument("--admin-email", default=None, help="Operator email authorized to create organization accounts; saved only in private instance config")
    for name, help_text in (("doctor", "Validate files and production safety gates"), ("plan", "Print a start plan without changing services"), ("status", "Show Compose status")):
        command = sub.add_parser(name, help=help_text)
        add_common(command)
        if name == "doctor":
            command.add_argument("--check-docker", action="store_true")
    for name, help_text in (("start", "Print a plan; apply only with --apply"), ("stop", "Print a stop plan; apply only with --apply")):
        command = sub.add_parser(name, help=help_text)
        add_common(command)
        command.add_argument("--apply", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return handle(args)
    except (ManagerError, OSError, ValueError) as exc:
        print(f"selfhost: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
