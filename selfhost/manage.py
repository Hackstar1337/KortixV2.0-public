def private_write(path: Path, text: str) -> None:
    """Write a generated private file without exposing its contents."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=f".{path.name}.", dir=str(path.parent), text=True)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(temporary, path)
        chmod_private(path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def chmod_private(path: Path) -> None:
    try:
        path.chmod(0o700 if path.is_dir() else 0o600)
    except OSError:
        # Windows ACLs are inherited. The manager still avoids printing values.
        pass


def read_json(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ManagerError(f"Cannot read config {path}: {exc}") from exc
    if not isinstance(value, dict):
        raise ManagerError(f"Config must be a JSON object: {path}")
    return value


def parse_env(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for number, raw in enumerate(path.read_text(encoding="utf-8-sig").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[7:].lstrip()
        key, separator, value = line.partition("=")
        if not separator or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key):
            raise ManagerError(f"Invalid environment line {number} in {path}")
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]
        values[key] = value
    return values


def write_env(path: Path, values: dict[str, str]) -> None:
    lines = ["# Generated by selfhost/manage.py. Keep this file private."]
    for key in sorted(values):
        value = values[key].replace("\\", "\\\\").replace("\n", "\\n")
        if any(char in value for char in " #\"'"):
            value = '"' + value.replace('"', '\\"') + '"'
        lines.append(f"{key}={value}")
    private_write(path, "\n".join(lines) + "\n")


def token(length: int = 32) -> str:
    return secrets.token_hex(length)


def supabase_jwt(role: str, secret: str) -> str:
    def encode(value: bytes) -> str:
        return base64.urlsafe_b64encode(value).decode().rstrip("=")
    header = encode(json.dumps({"alg":"HS256","typ":"JWT"}, separators=(",",":")).encode())
    payload = encode(json.dumps({"role":role,"iss":"supabase","iat":1641024000,"exp":2114380800}, separators=(",",":")).encode())
    body = header + "." + payload
    return body + "." + encode(hmac.new(secret.encode(), body.encode(), hashlib.sha256).digest())


def valid_supabase_jwt(value: str, role: str, secret: str) -> bool:
    try:
        header, payload, signature = value.split(".")
        meta = json.loads(base64.urlsafe_b64decode(header + "=" * (-len(header)%4)))
        claims = json.loads(base64.urlsafe_b64decode(payload + "=" * (-len(payload)%4)))
        expected = base64.urlsafe_b64encode(hmac.new(secret.encode(), (header+"."+payload).encode(), hashlib.sha256).digest()).decode().rstrip("=")
        return meta.get("alg")=="HS256" and claims.get("role")==role and hmac.compare_digest(signature, expected)
    except (ValueError, TypeError, KeyError):
        return False


def stable_callback(url: str, production: bool) -> tuple[bool, str]:
    parsed = urlparse(url)
    host = (parsed.hostname or "").lower().rstrip(".")
    if not parsed.scheme or not host:
        return False, "callback URL must include a scheme and hostname"
    if parsed.username or parsed.password or parsed.query or parsed.fragment:
        return False, "public origin must not contain credentials, query or fragment"
    if parsed.path not in ("", "/"):
        return False, "configure the public origin without a route suffix such as /v1/health"
    if parsed.scheme not in ("http", "https"):
        return False, "public origin must use HTTP or HTTPS"
    if production:
        try:
            if not ipaddress.ip_address(host).is_global:
                return False, "production callback cannot use localhost or loopback/private IPs"
        except ValueError:
            pass
        if parsed.scheme != "https":
            return False, "production callback must use HTTPS"
        if host in LOOPBACK_HOSTS or host.endswith(".localhost"):
            return False, "production callback cannot use localhost or loopback"
        if host.endswith(".trycloudflare.com") or host == "trycloudflare.com":
            return False, "production callback cannot use a Cloudflare Quick Tunnel"
        if parsed.username or parsed.password:
            return False, "callback URL must not contain credentials"
        if parsed.fragment:
            return False, "callback URL must not contain a fragment"
    return True, "ok"


def load_config(instance: Path) -> dict[str, Any]:
    config_path = instance / "config.json"
    if not config_path.is_file():
        raise ManagerError(f"Missing {config_path}; run init first")
    config = read_json(config_path)
    if config.get("schema_version") != SCHEMA_VERSION:
        raise ManagerError(f"Unsupported config schema in {config_path}")
    return config


def compose_path(instance: Path, config: dict[str, Any]) -> Path:
    path = Path(str(config.get("compose_file", DEFAULT_COMPOSE)))
    return path if path.is_absolute() else instance / path


def path_from_config(instance: Path, value: str | None) -> Path | None:
    if not value:
        return None
    path = Path(value)
    return path if path.is_absolute() else instance / path


def compose_variables(compose: str) -> set[str]:
    return {match.group(1) for match in re.finditer(r"\$\{([A-Z][A-Z0-9_]*)(?::-[^}]*)?\}", compose)}


